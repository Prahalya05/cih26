export const STRINGS: Record<LangCode, Partial<Strings>> = { en, ta, hi };
export type StringKey = keyof Strings;

export const LangContext = createContext<{ lang: LangCode; setLang: (l: LangCode) => void }>({
  lang: "ta",
  setLang: () => {},
});

export function useT() {
  const { lang } = useContext(LangContext);
  const t = (key: StringKey, vars: Record<string, string | number> = {}) =>
    (STRINGS[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  /** Pick the right language from a {en, ta, hi} object (English when the language is missing). */
  const pick = (o: { en: string; ta?: string | null; hi?: string | null }) => (lang === "ta" && o.ta) || (lang === "hi" && o.hi) || o.en;
  return { t, pick, lang };
}
