export const STRINGS: Record<LangCode, Strings> = { en, ta };
export type StringKey = keyof Strings;

export const LangContext = createContext<{ lang: LangCode; setLang: (l: LangCode) => void }>({
  lang: "ta",
  setLang: () => {},
});

export function useT() {
  const { lang } = useContext(LangContext);
  const t = (key: StringKey, vars: Record<string, string | number> = {}) =>
    STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  /** Pick the right language from a {en, ta} object. */
  const pick = (o: { en: string; ta?: string }) => (lang === "ta" && o.ta) || o.en;
  return { t, pick, lang };
}
